def scan_music_folder(folder: Path):
    tracks = []
    if not folder or not folder.is_dir():
        return tracks
    for p in sorted(folder.rglob('*')):
        if p.is_file() and p.suffix.lower() in AUDIO_EXTENSIONS:
            rel = p.relative_to(folder).as_posix()
            tracks.append({
                'id': len(tracks),
                'path': p,
                'fileName': p.name,
                'relativePath': rel,
                'fileSize': p.stat().st_size,
            })
    return tracks


def make_handler(folder: Path, tracks: list):
    tracks_by_id = {t['id']: t for t in tracks}

    class ArmoniaHandler(http.server.BaseHTTPRequestHandler):
        def log_message(self, format, *args):
            return  # Silenzia log HTTP rumorosi

        def do_GET(self):
            parsed = urllib.parse.urlparse(self.path)
            route = parsed.path

            if route in ('/', '/index.html'):
                self.send_response(200)
                self.send_header('Content-Type', 'text/html; charset=utf-8')
                self.send_header('Content-Length', str(len(HTML_BYTES)))
                self.send_header('Cache-Control', 'no-store')
                self.end_headers()
                self.wfile.write(HTML_BYTES)
                return

            if route == '/api/folder-tracks':
                payload = json.dumps({
                    'folder': str(folder) if folder else '',
                    'tracks': [
                        {
                            'fileName': t['fileName'],
                            'relativePath': t['relativePath'],
                            'fileSize': t['fileSize'],
                            'url': f"/media/{t['id']}",
                        }
                        for t in tracks
                    ],
                }).encode('utf-8')
                self.send_response(200)
                self.send_header('Content-Type', 'application/json; charset=utf-8')
                self.send_header('Content-Length', str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)
                return

            if route.startswith('/media/'):
                try:
                    tid = int(route.split('/media/', 1)[1])
                except ValueError:
                    self.send_error(404)
                    return
                item = tracks_by_id.get(tid)
                if not item or not item['path'].is_file():
                    self.send_error(404)
                    return
                self._serve_file_with_range(item['path'])
                return

            self.send_error(404)

        def _serve_file_with_range(self, file_path: Path):
            file_size = file_path.stat().st_size
            mime, _ = mimetypes.guess_type(str(file_path))
            content_type = mime or 'application/octet-stream'
            range_hdr = self.headers.get('Range')

            start = 0
            end = file_size - 1
            status = 200

            if range_hdr and range_hdr.startswith('bytes='):
                try:
                    spec = range_hdr.replace('bytes=', '').split(',')[0].strip()
                    s_part, e_part = spec.split('-', 1)
                    if s_part:
                        start = int(s_part)
                    if e_part:
                        end = min(int(e_part), file_size - 1)
                    if start > end or start >= file_size:
                        self.send_response(416)
                        self.send_header('Content-Range', f'bytes */{file_size}')
                        self.end_headers()
                        return
                    status = 206
                except ValueError:
                    start, end, status = 0, file_size - 1, 200

            length = end - start + 1
            self.send_response(status)
            self.send_header('Content-Type', content_type)
            self.send_header('Accept-Ranges', 'bytes')
            self.send_header('Content-Length', str(length))
            if status == 206:
                self.send_header('Content-Range', f'bytes {start}-{end}/{file_size}')
            self.end_headers()

            with open(file_path, 'rb') as f:
                f.seek(start)
                remaining = length
                while remaining > 0:
                    chunk = f.read(min(65536, remaining))
                    if not chunk:
                        break
                    try:
                        self.wfile.write(chunk)
                    except BrokenPipeError:
                        break
                    remaining -= len(chunk)

    return ArmoniaHandler


def find_free_port(preferred: int) -> int:
    if preferred > 0:
        return preferred
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


def open_app_window(url: str):
    """Prova ad aprire ArmoniaPlay come finestra desktop dedicata (--app), altrimenti usa il browser predefinito."""
    candidates = [
        'google-chrome', 'chromium', 'chromium-browser', 'microsoft-edge', 'msedge', 'brave-browser',
        '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
        '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
        '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',
    ]
    if sys.platform == 'win32':
        for base in [os.environ.get('PROGRAMFILES', ''), os.environ.get('PROGRAMFILES(X86)', ''), os.environ.get('LOCALAPPDATA', '')]:
            if base:
                candidates.extend([
                    os.path.join(base, 'Google', 'Chrome', 'Application', 'chrome.exe'),
                    os.path.join(base, 'Microsoft', 'Edge', 'Application', 'msedge.exe'),
                ])
    for exe in candidates:
        resolved = exe if os.path.isfile(exe) else shutil.which(exe)
        if resolved:
            try:
                subprocess.Popen(
                    [resolved, f'--app={url}', '--window-size=1280,860'],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
                return
            except OSError:
                continue
    webbrowser.open(url)


def main():
    parser = argparse.ArgumentParser(description='ArmoniaPlay — Player Musicale Locale Standalone / Offline Local Music Player')
    parser.add_argument('folder', nargs='?', default=None, help='Cartella musicale locale da caricare all avvio / Local music folder to autoload')
    parser.add_argument('--port', type=int, default=0, help='Porta locale (0 = automatica) / Local port (0 = auto)')
    parser.add_argument('--lang', choices=['it', 'en'], default=None, help='Lingua interfaccia iniziale (it o en) / Initial UI language (it or en)')
    parser.add_argument('--no-browser', action='store_true', help='Non aprire automaticamente la finestra / Do not open window automatically')
    args = parser.parse_args()

    folder = Path(args.folder).expanduser().resolve() if args.folder else None
    tracks = scan_music_folder(folder) if folder else []
    port = find_free_port(args.port)
    url = f'http://127.0.0.1:{port}/' + (f'?lang={args.lang}' if args.lang else '')
    is_en = args.lang == 'en'

    server = http.server.ThreadingHTTPServer(('127.0.0.1', port), make_handler(folder, tracks))
    print(f'ArmoniaPlay running at {url}' if is_en else f'ArmoniaPlay avviato su {url}')
    if folder:
        print(
            f'Loaded folder: {folder} ({len(tracks)} tracks found)'
            if is_en
            else f'Cartella caricata: {folder} ({len(tracks)} brani trovati)'
        )
    print('Press Ctrl+C to quit.' if is_en else 'Premi Ctrl+C per chiudere.')

    if not args.no_browser:
        threading.Timer(0.35, open_app_window, args=(url,)).start()

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print('\nClosing ArmoniaPlay...' if is_en else '\nChiusura ArmoniaPlay...')
    finally:
        server.server_close()


if __name__ == '__main__':
    main()
